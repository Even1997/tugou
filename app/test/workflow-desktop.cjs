const { app, clipboard } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
if (!process.env.TUGOU_DATA_DIR || !require('./qa-paths.cjs').inside(process.env.TUGOU_DATA_DIR)) throw new Error('Isolated QA profile required');
const output = path.resolve(__dirname, '../test-results');
const report = { checks: [], errors: [] };
// Exercise the real IPC/UI path without replacing the user's system clipboard during QA.
let copiedText = '';
clipboard.writeText = (text) => { copiedText = text; };
const timeout = setTimeout(() => { console.error('Workflow QA timeout'); app.exit(1); }, 60000);
app.on('browser-window-created', (_event, window) => {
  window.webContents.on('console-message', (_event, details) => { if (details.level === 'error') report.errors.push(details.message); });
  window.webContents.once('did-finish-load', async () => {
    const js = (code) => window.webContents.executeJavaScript(code, true);
    const wait = async (expression) => { for (let attempt = 0; attempt < 100; attempt++) { if (await js(expression)) return; await new Promise((resolve) => setTimeout(resolve, 50)); } throw new Error(`Timed out: ${expression}`); };
    const click = async (selector, text) => { await wait(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).some(el => ${text ? `el.textContent.trim() === ${JSON.stringify(text)}` : 'true'})`); await js(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(el => ${text ? `el.textContent.trim() === ${JSON.stringify(text)}` : 'true'}).click()`); };
    const fill = async (selector, value, textarea = false) => { await wait(`document.querySelector(${JSON.stringify(selector)}) !== null`); await js(`{ const input = document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(${textarea ? 'HTMLTextAreaElement' : 'HTMLInputElement'}.prototype, 'value').set.call(input, ${JSON.stringify(value)}); input.dispatchEvent(new Event('input', { bubbles: true })); }`); };
    const check = (label, value) => { assert.ok(value, label); report.checks.push(label); };
    const save = async () => { await click('.toolbar-end button', '保存'); await wait('document.querySelector("[role=status]")?.textContent === "已保存"'); };
    const point = async (selector) => { await new Promise((resolve) => setTimeout(resolve, 100)); return js(`{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();({x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)})}`); };
    const geometry = () => js(`Array.from(document.querySelectorAll('.react-flow__node')).map(el=>({id:el.dataset.id,position:el.style.transform,rect:JSON.stringify(el.getBoundingClientRect()),zoom:devicePixelRatio,innerWidth}))`);
    const drag = async (from, to) => {
      window.webContents.sendInputEvent({ type: 'mouseMove', ...from });
      window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...from });
      for (let i = 1; i <= 8; i++) { window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(from.x + (to.x - from.x) * i / 8), y: Math.round(from.y + (to.y - from.y) * i / 8), modifiers: ['leftButtonDown'] }); await new Promise((resolve) => setTimeout(resolve, 16)); }
      window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...to });
    };
    try {
      await fs.mkdir(output, { recursive: true });
      await wait('document.querySelector(".toolbar")');
      const all = await js('window.tugou.list()');
      let imported;
      for (const item of all) { const record = await js(`window.tugou.open(${JSON.stringify(item.id)})`); if (record.document.assets.length === 4) { imported = record; break; } }
      assert.ok(imported);
      const created = await js('window.tugou.create("配方画布验证")');
      const document = { ...created.document, modules: [
        { id: 'm-style', name: '画风模块', kind: 'style', text: '清线画风', global: true },
        { id: 'm-person', name: '人物模块', kind: 'character', text: '人物初版', global: false },
        { id: 'm-pose', name: '动作模块', kind: 'action', text: '并肩站立', global: false }],
        recipes: [{ id: 'recipe', name: '人物配方', moduleIds: ['m-person'], references: [{ assetId: imported.document.assets[0].id, role: '身份' }], output: '完整全身', size: '2048x3072', originalMetadata: { retained: true } }],
        assets: imported.document.assets, layers: [{ id: 'legacy-layer', kind: 'image', mask: { paths: [[1, 2]] }, unknown: true }], canvasProjectIds: ['legacy-unmigrated-id'], unknown: { preserve: true } };
      await js(`window.tugou.save(${JSON.stringify(created.id)}, ${JSON.stringify(document)}, 1)`);
      await click('.project-menu button', '新建');
      await wait(`Array.from(document.querySelector('select[aria-label=当前工程]').options).some(option => option.value === ${JSON.stringify(created.id)})`);
      await js(`{const select=document.querySelector('select[aria-label=当前工程]');select.value=${JSON.stringify(created.id)};select.dispatchEvent(new Event('change',{bubbles:true}));}`);
      await wait('document.querySelector("input[aria-label=工程名称]").value === "配方画布验证"');
      await js("document.querySelector('.complete-prompt').open=true");
      await wait('document.querySelector("select[aria-label=当前配方]")?.value === "recipe"');
      await fill('textarea[aria-label=构图与输出]', '全身构图，保留留白', true);
      await fill('input[aria-label=参考图1职责]', '仅身份，不采用背景');
      await js(`Array.from(document.querySelectorAll('.module-picker label')).find(label=>label.textContent.includes('动作模块')).querySelector('input').click()`);
      await wait('document.querySelector("textarea[aria-label=合成提示词]").value.includes("并肩站立")');
      const preview = await js('document.querySelector("textarea[aria-label=合成提示词]").value');
      await click('.prompt-preview button', '复制');
      await wait('document.querySelector(".prompt-preview button").textContent.trim() === "已复制"');
      check('copy uses the validated main-process clipboard bridge', copiedText === preview);
      check('recipe modules, output and image role compose in UI', preview.includes('仅身份，不采用背景') && preview.includes('全身构图，保留留白'));
      check('shared style appears once at the end', preview.indexOf('清线画风') > preview.indexOf('全身构图') && preview.split('清线画风').length === 2);
      await new Promise((resolve) => setTimeout(resolve, 120)); await fs.writeFile(path.join(output, 'recipes.png'), (await window.webContents.capturePage()).toPNG());
      await click('.recipe-editor .editor-heading button', '加入画布');
      await wait('document.querySelectorAll(".react-flow__node").length === 1');
      const recipeNodeId = await js('document.querySelector(".react-flow__node").dataset.id');
      await click('.palette-tabs button', '模块'); await click('.palette-item', '人物模块');
      await wait('document.querySelectorAll(".react-flow__node").length === 2');
      const moduleNodeId = await js(`Array.from(document.querySelectorAll('.react-flow__node')).find(node=>node.textContent.includes('人物模块')).dataset.id`);
      const recipeSelector = `.react-flow__node[data-id="${recipeNodeId}"]`, moduleSelector = `.react-flow__node[data-id="${moduleNodeId}"]`;
      report.beforeDrag = await geometry();
      const rp = await point(`${recipeSelector} header`);
      await drag(rp, { x: rp.x + 280, y: rp.y + 180 });
      report.afterRecipeDrag = await geometry();
      const mp = await point(`${moduleSelector} header`);
      await drag(mp, { x: mp.x - 120, y: mp.y - 50 });
      report.afterModuleDrag = await geometry();
      await drag(await point(`${moduleSelector} .source`), await point(`${recipeSelector} .target`));
      await wait('document.querySelectorAll(".react-flow__edge").length === 1');
      check('native pointer drag moves nodes and connects handles', true);
      await js(`{const target=document.querySelector('.flow-surface'),r=target.getBoundingClientRect(),transfer=new DataTransfer();transfer.setData('application/x-tugou',JSON.stringify({projectId:${JSON.stringify(created.id)},type:'module',id:'m-pose'}));target.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer,clientX:r.x+80,clientY:r.y+300}));}`);
      await wait('document.querySelectorAll(".react-flow__node").length === 3');
      check('module drag-drop adds a persisted canvas node', true);
      await click('nav button', '提示词工作台');
      await js(`Array.from(document.querySelectorAll('.module-list .module')).find(button=>button.textContent.includes('人物模块')).click()`);
      await fill('textarea[aria-label=模块提示词]', '人物第二版', true);
      await click('nav button', '无限画布');
      await wait('document.querySelector(".canvas-body").textContent.includes("有新版")');
      check('workbench changes mark canvas references outdated', true);
      await js(`Array.from(document.querySelectorAll('.workflow-toolbar button')).find(button=>button.textContent.startsWith('更新引用')).click()`);
      await wait(`document.querySelector(${JSON.stringify(moduleSelector)}).textContent.includes('人物第二版')`);
      await click(moduleSelector);
      await click('.canvas-inspector .binding-heading button', '本地修改');
      await fill('.canvas-inspector textarea', '单张人物覆盖', true);
      await click('nav button', '提示词工作台'); await fill('textarea[aria-label=模块提示词]', '人物第三版', true);
      await click('nav button', '无限画布');
      await wait(`document.querySelector(${JSON.stringify(moduleSelector)}).textContent.includes('修改冲突')`);
      await js(`Array.from(document.querySelectorAll('.workflow-toolbar button')).find(button=>button.textContent.startsWith('更新引用')).click()`);
      check('bulk update preserves conflicting node text', await js(`document.querySelector(${JSON.stringify(moduleSelector)}).textContent.includes('单张人物覆盖')`));
      await click(moduleSelector);
      await click('.binding-resolution button', '保留本地并同步版本');
      await wait(`document.querySelector(${JSON.stringify(moduleSelector)}).textContent.includes('本地修改')`);
      check('local conflict resolves explicitly without losing the override', true);
      await click(recipeSelector);
      await wait('document.querySelector(".canvas-inspector textarea[aria-label=合成提示词]") !== null');
      check('connected override participates in final canvas prompt', await js('document.querySelector(".canvas-inspector textarea[aria-label=合成提示词]").value.includes("单张人物覆盖")'));
      await fs.writeFile(path.join(output, 'canvas.png'), (await window.webContents.capturePage()).toPNG());
      await click(moduleSelector);
      await click('#canvas-actions button', '删除所选');
      await wait('document.querySelectorAll(".react-flow__node").length === 2');
      check('delete removes connected edges', await js('document.querySelectorAll(".react-flow__edge").length === 0'));
      await click('button[aria-label=撤销]');
      await wait('document.querySelectorAll(".react-flow__node").length === 3 && document.querySelectorAll(".react-flow__edge").length === 1');
      check('undo restores nodes, connections and overridden content', await js(`document.querySelector(${JSON.stringify(moduleSelector)}).textContent.includes('单张人物覆盖')`));
      await click('button[aria-label=重做]'); await wait('document.querySelectorAll(".react-flow__node").length === 2'); await click('button[aria-label=撤销]');
      await click(recipeSelector);
      const selectPoint = await point(`${moduleSelector} header`);
      window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Shift' });
      window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...selectPoint, modifiers: ['shift'] });
      window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...selectPoint, modifiers: ['shift'] });
      window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Shift' });
      await wait('document.querySelectorAll(".react-flow__node.selected").length === 2');
      const beforeGroup = await geometry(), groupPoint = await point(`${moduleSelector} header`);
      await drag(groupPoint, { x: groupPoint.x + 70, y: groupPoint.y + 35 });
      await new Promise((resolve) => setTimeout(resolve, 100));
      const afterGroup = await geometry();
      check('shift selection and group dragging move both nodes', [recipeNodeId, moduleNodeId].every((id) => beforeGroup.find((entry) => entry.id === id).position !== afterGroup.find((entry) => entry.id === id).position));
      await click('#canvas-actions button', '适应画布');
      await new Promise((resolve) => setTimeout(resolve, 200));
      await save();
      const saved = await js(`window.tugou.open(${JSON.stringify(created.id)})`);
      check('saved canvas retains node positions and edges', saved.document.tugouCanvas.nodes.length === 3 && saved.document.tugouCanvas.edges.length === 1 && saved.document.tugouCanvas.nodes[0].position.x > 60);
      for (const key of ['layers', 'assets', 'canvasProjectIds', 'unknown']) assert.deepEqual(saved.document[key], document[key]);
      check('existing layers, asset metadata, old canvas links and unknown fields survive editing', true);
      assert.deepEqual(saved.document.recipes[0].originalMetadata, { retained: true });
      window.setSize(960, 720); await new Promise((resolve) => setTimeout(resolve, 150));
      await click('#canvas-actions button', '适应画布'); await new Promise((resolve) => setTimeout(resolve, 200));
      check('960px canvas stays within window', await js('document.documentElement.scrollWidth === innerWidth'));
      await fs.writeFile(path.join(output, 'canvas-960.png'), (await window.webContents.capturePage()).toPNG());
      await save();
      await click('nav button', '提示词工作台'); await js("document.querySelector('.complete-prompt').open=true");
      await click('button[aria-label=新建配方]');
      await click('button[aria-label=配方设置]');
      await fill('input[aria-label=配方名称]', '临时配方验收');
      await click('button[aria-label=配方设置]');
      await js(`{const select=document.querySelector('select[aria-label=添加参考图]');select.value=${JSON.stringify(imported.document.assets[1].id)};select.dispatchEvent(new Event('change',{bubbles:true}));}`);
      await wait('document.querySelector("input[aria-label=参考图1职责]") !== null');
      await click('button[aria-label=移除参考图1]');
      await wait('document.querySelector("input[aria-label=参考图1职责]") === null');
      await js('window.confirm = () => true; void 0');
      await click('button[aria-label=配方设置]');
      await click('.tool-popover button', '删除配方');
      await wait('document.querySelector("select[aria-label=当前配方]").options.length === 1');
      check('recipe create, rename, reference add/remove and delete work in UI', true);
      await save();
      await click('nav button', '无限画布');
      check('no renderer errors', report.errors.length === 0);
      report.projectId = saved.id; report.verifiedAt = new Date().toISOString();
      await fs.writeFile(path.join(output, 'workflow-desktop.json'), JSON.stringify(report, null, 2));
      console.log(JSON.stringify(report)); clearTimeout(timeout); await js('window.tugou.window("close")');
    } catch (error) {
      report.failure = error.message; await fs.writeFile(path.join(output, 'workflow-desktop.json'), JSON.stringify(report, null, 2));
      await fs.writeFile(path.join(output, 'workflow-failure.png'), (await window.webContents.capturePage()).toPNG()); console.error(error.message); clearTimeout(timeout); app.exit(1);
    }
  });
});
require('../main.cjs');
