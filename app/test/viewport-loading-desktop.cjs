const {app}=require('electron'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const {Client}=require('@modelcontextprotocol/sdk/client/index.js'),{StdioClientTransport}=require('@modelcontextprotocol/sdk/client/stdio.js');
const {ProjectStore,hash}=require('../core/storage.cjs'),pages=require('../core/pages.cjs'),{createLayer}=require('../core/layers.cjs');
const profile=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'tugou-viewport-loading-'));
const output=path.resolve('test-results/viewport-loading.json'),main=path.resolve('desktop-main.cjs');
app.setAppPath(path.dirname(main));process.env.TUGOU_DATA_DIR=profile;process.argv.push('--mcp-enable');
fs.writeFileSync(path.join(profile,'preferences.json'),JSON.stringify({...require('../core/preference-values.cjs').defaults,autoCheck:false}));
const report={checks:[],errors:[]},delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let transport;
const finish=code=>{fs.mkdirSync(path.dirname(output),{recursive:true});fs.writeFileSync(output,JSON.stringify(report,null,2));transport?.close();app.exit(code);};
setTimeout(()=>{report.failure='timeout';finish(1);},75000).unref();
app.on('browser-window-created',(_,w)=>{
  if(w.webContents.getType()!=='window')return;
  w.webContents.setBackgroundThrottling(false);
  w.webContents.on('console-message',e=>{if(e.level==='error')report.errors.push(e.message);});
  const resources=[];
  w.webContents.debugger.attach('1.3');
  w.webContents.debugger.on('message',(_,method,data)=>{if(method==='Network.requestWillBeSent'&&data.request.url.startsWith('tugou-media:'))resources.push(data.request.url);});
  const networking=w.webContents.debugger.sendCommand('Network.enable');
  w.webContents.once('did-finish-load',async()=>{
    const js=code=>w.webContents.executeJavaScript(code,true);
    const wait=async(name,test)=>{for(let n=0;n<160;n++){if(await test()){report.checks.push(name);return;}await delay(40);}throw Error(name);};
    try{
      await networking;
      await wait('desktop shell',()=>js(`!!document.querySelector('.workspace-rail')`));
      await wait('stdio session',()=>fs.existsSync(path.join(profile,'mcp-session.json')));
      transport=new StdioClientTransport({command:process.execPath,args:[path.resolve('core/mcp.cjs'),'--session',path.join(profile,'mcp-session.json')],env:{...process.env,ELECTRON_RUN_AS_NODE:'1'},stderr:'pipe'});
      const client=new Client({name:'viewport-loading-qa',version:'1'});await client.connect(transport);
      const call=async(name,args={})=>{const r=await client.callTool({name,arguments:args});if(r.isError)throw Object.assign(Error(r.content[0]?.text),r.structuredContent?.error);return r;};
      const state=async()=>(await call('get_state')).structuredContent;
      const run=async(command,args={})=>(await call('run_command',{command,args,expectedRevision:(await state()).revision}));
      const store=new ProjectStore(path.join(profile,'workspace'));await store.init();const project=await store.create('视口分级加载验收');
      const make=async(id,background)=>{const bytes=await require('sharp')({create:{width:4000,height:4000,channels:4,background}}).png().toBuffer();
        const resource=hash(bytes)+'.png';fs.writeFileSync(path.join(store.root,'resources',resource),bytes);return {id,name:id,width:4000,height:4000,resource};};
      const [near,far]=await Promise.all([make('visible',{r:184,g:20,b:60,alpha:1}),make('outside',{r:21,g:140,b:70,alpha:1})]);
      const scope={...project.document,assets:[near,far]},second=pages.create(scope,'canvas','加载验证画布'),third=pages.create(second.document,'layers','加载验证图层');
      const doc=third.document;
      doc.tugouCanvas={version:1,edges:[],viewport:{x:46,y:52,zoom:.2},nodes:[near,far].map((a,i)=>({id:a.id,type:'asset',position:{x:i*25000,y:0},data:{assetId:a.id,role:'参考'}}))};
      doc.width=4000;doc.height=4000;doc.compositionView={x:50,y:45,zoom:.03};
      doc.layers=[near,far].map((a,i)=>createLayer('image',{id:`layer-${a.id}`,assetId:a.id,x:i*25000,y:0,width:3600,height:3600}));
      await store.save(project.id,doc,project.revision);
      await run('project.open',{id:project.id});
      await run('page.activate',{kind:'canvas',id:second.id});
      await wait('low zoom placeholders, offscreen canvas node unmounted',()=>js(`!!document.querySelector('[data-id="visible"] .canvas-media-placeholder')&&!document.querySelector('[data-id="outside"]')`));
      await run('canvas.viewport',{x:46,y:52,zoom:1});
      await wait('normal zoom thumbnail',()=>js(`document.querySelector('[data-id="visible"] img')?.naturalWidth>0`));
      assert.match(await js(`document.querySelector('[data-id="visible"] img').src`),/tugou-media:\/\/resource\//);
      await run('page.activate',{kind:'layers',id:third.id});
      await wait('overview raster requests a bounded thumbnail for the visible photo',()=>resources.some(url=>url.includes(near.resource+'?preview=')));
      assert.ok(!resources.some(url=>url.includes(far.resource)&&(url.includes('?preview=')||url.includes('://original/'))));
      report.checks.push('offscreen layer requests no bitmap');
      const link=await js(`fetch('tugou-media://resource/${near.resource}?preview=96').then(r=>r.blob()).then(createImageBitmap).then(i=>{const s=[i.width,i.height];i.close();return s;})`);
      assert.deepEqual(link,[96,96]);
      await js(`(()=>{const s=document.querySelector('.layer-stage'),r=s.getBoundingClientRect();s.dispatchEvent(new WheelEvent('wheel',{ctrlKey:true,deltaY:-1500,clientX:r.left+95,clientY:r.top+85,bubbles:true,cancelable:true}));})()`);
      await wait('zooming in restores the original photo',()=>resources.some(url=>url.includes(`tugou-media://original/${near.resource}`)));
      const b=(await run('artboard.create',{name:'原图输出核对',width:200,height:200})).structuredContent.id;
      await run('layer.create',{artboardId:b,kind:'image',properties:{assetId:near.id,x:0,y:0,width:200,height:200}});
      await run('artboard.export',{artboardId:b,path:'source-quality.png'});
      const outputPixels=await require('sharp')(path.join((await state()).filesRoot,'source-quality.png')).extract({left:100,top:100,width:1,height:1}).ensureAlpha().raw().toBuffer();
      assert.deepEqual([...outputPixels],[184,20,60,255]);
      report.checks.push('export requests original photo');
      await run('project.save');await run('project.open',{id:project.id});
      await run('page.activate',{kind:'layers',id:'composition-main'});
      await run('page.activate',{kind:'canvas',id:'canvas-main'});
      await assert.rejects(run('asset.delete',{ids:[near.id]}),/仍被/);
      await run('page.activate',{kind:'canvas',id:second.id});
      assert.equal((await state()).counts.nodes,2);
      report.checks.push('MCP reopens a deferred page and protects assets used on it');
      assert.deepEqual(report.errors,[]);finish(0);
    }catch(error){report.failure=error.stack;report.resources=resources;report.layerState=await js(`({transform:document.querySelector('.layer-overlay > g')?.getAttribute('transform'),rendering:document.querySelector('canvas[data-rendering]')?.dataset.rendering,alert:document.querySelector('.message.error')?.textContent})`).catch(()=>null);finish(1);}
  });
});
require(main);
